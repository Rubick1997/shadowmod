-- shadowmod: shadow banning kit for Postgres 16.
--
-- Nothing is rejected on save. The app scores text with a decision model,
-- appends raw scores here, and one view (shadowmod.hidden) decides what other
-- people can see. Authors always see their own rows.
--
-- Design priority: keep false positives low and findable.
--   * thresholds live in shadowmod.policy, one per question, and default high
--   * a review band keeps borderline rows visible until a human decides
--   * error / refused checks never hide anything and never un-hide anything
--   * raw probabilities are kept, so thresholds can be changed and simulated
--     without calling a model again
--
-- Safe to apply more than once.

CREATE SCHEMA IF NOT EXISTS shadowmod;

DO $$ BEGIN
  CREATE TYPE shadowmod.check_status AS ENUM ('scored', 'refused', 'error', 'override');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE shadowmod.verdict AS ENUM ('hide', 'show');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- What is moderated. Moderating a new column is a new row here, not a schema change.
CREATE TABLE IF NOT EXISTS shadowmod.target (
  id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name  text NOT NULL,
  column_name text NOT NULL,
  UNIQUE (table_name, column_name)
);

-- One row per check. Append-only (enforced by trigger below).
-- No foreign key to the content table: the evidence survives edits and deletes.
CREATE TABLE IF NOT EXISTS shadowmod.check (
  id               bigserial PRIMARY KEY,
  target_id        smallint NOT NULL REFERENCES shadowmod.target (id),
  row_key          text NOT NULL,              -- int or uuid keys, as text
  author_key       text,
  status           shadowmod.check_status NOT NULL,
  override_verdict shadowmod.verdict,          -- only for status = 'override'
  moderator        text,
  note             text,
  content_hash     text,
  content_snapshot text,                       -- the exact text that was checked
  provider         text,
  model            text,
  latency_ms       int,
  error            jsonb,
  checked_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT check_override_has_verdict
    CHECK ((status = 'override') = (override_verdict IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS check_row_latest_idx
  ON shadowmod.check (target_id, row_key, id DESC)
  WHERE status IN ('scored', 'override');

CREATE INDEX IF NOT EXISTS check_row_hash_idx
  ON shadowmod.check (target_id, row_key, content_hash);

-- Raw probabilities, one row per answered question. A refused question has no row.
-- Questions are open-ended text, not fixed columns.
CREATE TABLE IF NOT EXISTS shadowmod.check_score (
  check_id    bigint NOT NULL REFERENCES shadowmod.check (id),
  question    text NOT NULL,
  probability numeric(5,4) NOT NULL CHECK (probability BETWEEN 0 AND 1),
  PRIMARY KEY (check_id, question)
);

-- Thresholds, one per question. Not in prompts, not in code.
-- A question with no policy row (or enabled = false) is recorded but never hides.
CREATE TABLE IF NOT EXISTS shadowmod.policy (
  question    text PRIMARY KEY,
  hide_at     numeric(5,4) NOT NULL CHECK (hide_at BETWEEN 0 AND 1),
  review_from numeric(5,4) NOT NULL CHECK (review_from BETWEEN 0 AND 1),
  enabled     boolean NOT NULL DEFAULT true,
  CHECK (review_from <= hide_at)
);

-- Conservative defaults that favour precision over recall: a high bar to hide,
-- and a wide review band below it. Borderline rows stay visible and go to a
-- human. Tune these from bench/ results and simulate_policy(), never by guessing.
INSERT INTO shadowmod.policy (question, hide_at, review_from) VALUES
  ('abusive',            0.9500, 0.5000),
  ('offsite_contact',    0.9500, 0.5000),
  ('adult_solicitation', 0.9500, 0.5000)
ON CONFLICT (question) DO NOTHING;

-- User-level shadow ban: everything they write is hidden from others.
CREATE TABLE IF NOT EXISTS shadowmod.held_author (
  author_key text PRIMARY KEY,
  reason     text,
  held_at    timestamptz NOT NULL DEFAULT now()
);

-- Append-only log: humans and the model share one history.
CREATE OR REPLACE FUNCTION shadowmod.forbid_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'shadowmod.% is append-only', TG_TABLE_NAME;
END $$;

CREATE OR REPLACE TRIGGER check_append_only
  BEFORE UPDATE OR DELETE ON shadowmod.check
  FOR EACH ROW EXECUTE FUNCTION shadowmod.forbid_mutation();

CREATE OR REPLACE TRIGGER check_score_append_only
  BEFORE UPDATE OR DELETE ON shadowmod.check_score
  FOR EACH ROW EXECUTE FUNCTION shadowmod.forbid_mutation();

-- Latest decisive check per row.
--  * Only 'scored' and 'override' rows count. 'error' and 'refused' rows never
--    replace an earlier result and never hide anything on their own.
--  * A human override sticks to the exact text it was made on: a later 'scored'
--    check of the same content_hash (e.g. a re-run on a new model) does not
--    replace it. An edit (new hash) that is re-scored does.
CREATE OR REPLACE VIEW shadowmod.latest_check AS
SELECT DISTINCT ON (c.target_id, c.row_key) c.*
FROM shadowmod.check c
WHERE c.status IN ('scored', 'override')
  AND NOT (
    c.status = 'scored'
    AND EXISTS (
      SELECT 1 FROM shadowmod.check o
      WHERE o.target_id = c.target_id
        AND o.row_key = c.row_key
        AND o.status = 'override'
        AND o.content_hash IS NOT DISTINCT FROM c.content_hash
    )
  )
ORDER BY c.target_id, c.row_key, c.id DESC;

-- What is hidden from everyone but the author. Plain view so the planner can
-- inline it into NOT EXISTS (...) on every public read.
-- An override 'show' always wins: it is never hidden, whatever the scores.
CREATE OR REPLACE VIEW shadowmod.hidden AS
SELECT lc.target_id, lc.row_key, lc.author_key, lc.id AS check_id
FROM shadowmod.latest_check lc
WHERE (lc.status = 'override' AND lc.override_verdict = 'hide')
   OR (lc.status = 'scored' AND EXISTS (
        SELECT 1
        FROM shadowmod.check_score s
        JOIN shadowmod.policy p ON p.question = s.question AND p.enabled
        WHERE s.check_id = lc.id
          AND s.probability >= p.hide_at));

-- Borderline rows: visible, waiting for a human. Not hidden, not overridden.
CREATE OR REPLACE VIEW shadowmod.needs_review AS
SELECT lc.target_id, t.table_name, t.column_name, lc.row_key, lc.author_key,
       lc.id AS check_id, lc.checked_at, lc.content_snapshot,
       (SELECT jsonb_object_agg(s.question, s.probability)
          FROM shadowmod.check_score s WHERE s.check_id = lc.id) AS scores
FROM shadowmod.latest_check lc
JOIN shadowmod.target t ON t.id = lc.target_id
WHERE lc.status = 'scored'
  AND EXISTS (
    SELECT 1 FROM shadowmod.check_score s
    JOIN shadowmod.policy p ON p.question = s.question AND p.enabled
    WHERE s.check_id = lc.id
      AND s.probability >= p.review_from AND s.probability < p.hide_at)
  AND NOT EXISTS (
    SELECT 1 FROM shadowmod.check_score s
    JOIN shadowmod.policy p ON p.question = s.question AND p.enabled
    WHERE s.check_id = lc.id AND s.probability >= p.hide_at);

-- Random sample of currently hidden rows, for regular false-positive spot checks.
-- Use with LIMIT:  SELECT * FROM shadowmod.hidden_audit LIMIT 20;
CREATE OR REPLACE VIEW shadowmod.hidden_audit AS
SELECT h.target_id, t.table_name, t.column_name, h.row_key, h.author_key,
       c.id AS check_id, c.status, c.override_verdict, c.moderator,
       c.checked_at, c.content_snapshot,
       (SELECT jsonb_object_agg(s.question, s.probability)
          FROM shadowmod.check_score s WHERE s.check_id = c.id) AS scores
FROM shadowmod.hidden h
JOIN shadowmod.check c ON c.id = h.check_id
JOIN shadowmod.target t ON t.id = h.target_id
ORDER BY random();

-- Get or create a target id.
CREATE OR REPLACE FUNCTION shadowmod.target_id(p_table text, p_column text)
RETURNS smallint LANGUAGE sql AS $$
  WITH ins AS (
    INSERT INTO shadowmod.target (table_name, column_name)
    VALUES (p_table, p_column)
    ON CONFLICT (table_name, column_name) DO NOTHING
    RETURNING id)
  SELECT id FROM ins
  UNION ALL
  SELECT id FROM shadowmod.target WHERE table_name = p_table AND column_name = p_column
  LIMIT 1
$$;

-- A human decision. Appends an 'override' row carrying the content it was made
-- on (copied from the latest check of any status), so the log stays complete.
CREATE OR REPLACE FUNCTION shadowmod.override(
  p_target    smallint,
  p_row_key   text,
  p_verdict   shadowmod.verdict,
  p_moderator text,
  p_note      text DEFAULT NULL
) RETURNS bigint LANGUAGE sql AS $$
  INSERT INTO shadowmod.check
    (target_id, row_key, author_key, status, override_verdict, moderator, note,
     content_hash, content_snapshot)
  SELECT p_target, p_row_key, prev.author_key, 'override', p_verdict, p_moderator, p_note,
         prev.content_hash, prev.content_snapshot
  FROM (SELECT 1) one
  LEFT JOIN LATERAL (
    SELECT author_key, content_hash, content_snapshot
    FROM shadowmod.check
    WHERE target_id = p_target AND row_key = p_row_key
    ORDER BY id DESC LIMIT 1
  ) prev ON true
  RETURNING id
$$;

-- What would change if one question's hide_at were different, computed from
-- stored scores only: no model call. Treats the question as enabled.
CREATE OR REPLACE FUNCTION shadowmod.simulate_policy(p_question text, p_hide_at numeric)
RETURNS TABLE (currently_hidden bigint, would_hide bigint, newly_hidden bigint, newly_unhidden bigint)
LANGUAGE sql STABLE AS $$
  WITH flags AS (
    SELECT lc.id,
           (lc.status = 'override' AND lc.override_verdict = 'hide') AS by_override,
           lc.status = 'scored' AND coalesce(bool_or(
             s.probability >= CASE WHEN p.enabled THEN p.hide_at END), false) AS now_hidden,
           lc.status = 'scored' AND coalesce(bool_or(
             s.probability >= CASE WHEN s.question = p_question THEN p_hide_at
                                   WHEN p.enabled THEN p.hide_at END), false) AS then_hidden
    FROM shadowmod.latest_check lc
    LEFT JOIN shadowmod.check_score s ON s.check_id = lc.id
    LEFT JOIN shadowmod.policy p ON p.question = s.question
    GROUP BY lc.id, lc.status, lc.override_verdict
  )
  SELECT count(*) FILTER (WHERE by_override OR now_hidden),
         count(*) FILTER (WHERE by_override OR then_hidden),
         count(*) FILTER (WHERE NOT by_override AND then_hidden AND NOT now_hidden),
         count(*) FILTER (WHERE NOT by_override AND now_hidden AND NOT then_hidden)
  FROM flags
$$;
